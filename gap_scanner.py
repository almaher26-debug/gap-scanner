    vol_rel = None
    if "Volume" in df and len(df) > 2:
        avg = df["Volume"].iloc[-21:-1].astype(float).mean()
        vol_rel = float(t["Volume"]) / avg if avg > 0 else None
    return {"y_low": y_low, "low": low, "close": close,
            "depth": (y_low - low) / y_low * 100, "vol_rel": vol_rel}


