def sr_levels(df, today):
    """df = شموع يومية. يرجع مستويات الأسبوع السابق والشهر السابق + شمعة اليوم.
    {"W": (قمة، قاع، بداية الفترة)، "M": (...)، "high": أعلى اليوم، "low": أقل اليوم، "close": السعر}"""
    df = df.dropna(subset=OHLC)
    if df.empty:
        return None
    days = pd.DatetimeIndex([pd.Timestamp(pd.Timestamp(d).date()) for d in df.index])
    df = df.set_index(days)
    today = pd.Timestamp(today)
    week_start = today - pd.Timedelta(days=today.weekday())
    month_start = today.replace(day=1)
    out = {}
    prev_w = df[(df.index < week_start) & (df.index >= week_start - pd.Timedelta(days=7))]
    if not prev_w.empty:
        out["W"] = (float(prev_w["High"].max()), float(prev_w["Low"].min()), week_start)
    pm_start = (month_start - pd.Timedelta(days=1)).replace(day=1)
    prev_m = df[(df.index < month_start) & (df.index >= pm_start)]
    if not prev_m.empty:
        out["M"] = (float(prev_m["High"].max()), float(prev_m["Low"].min()), month_start)
    cur = df[df.index == today]
    if cur.empty:
        return None                                   # ما فيه شمعة اليوم (السوق ما فتح)
    out.update(high=float(cur["High"].iloc[-1]), low=float(cur["Low"].iloc[-1]),
               close=float(cur["Close"].iloc[-1]))
    return out


def check_sr(lv, tol=None):
    """يرجع قائمة اللمسات: [(الفريم W/M، "res"/"sup"، المستوى)]."""
    tol = SR_TOLERANCE if tol is None else tol
    hits = []
    for fr in ("W", "M"):
        if fr not in lv:
            continue
        hi, lo, _ = lv[fr]
        if lv["high"] >= hi * (1 - tol):
            hits.append((fr, "res", hi))
        if lv["low"] <= lo * (1 + tol):
            hits.append((fr, "sup", lo))
    return hits


def _sr_message(t, fr, kind, level, lv):
    frame = "الأسبوع السابق" if fr == "W" else "الشهر السابق"
    hi, lo, _ = lv[fr]
    if kind == "res":
        head = f"🔴 لمس مقاومة - قمة {frame}"
    else:
        head = f"🟢 لمس دعم - قاع {frame}"
    px = lv["close"]
    return (f"{head}\n"
            f"السهم: ${t}\n"
            f"المستوى: {level:.2f}\n"
            f"السعر الحين: {px:.2f} ({(px / level - 1) * 100:+.2f}% عن المستوى)\n"
            f"{frame}: قمة {hi:.2f} | قاع {lo:.2f}\n"
            f"اليوم: أعلى {lv['high']:.2f} | أقل {lv['low']:.2f}\n"
            f"الوقت: {pd.Timestamp.now(tz=LOCAL_TZ):%H:%M} (توقيتك)")


def scan_sr(tickers, already_sent):
    hits = 0
    today = pd.Timestamp.now(tz=NY).date()
    for t, df in download_batches(tickers, 50, period="3mo", interval="1d", prepost=False):
        try:
            lv = sr_levels(df, today)
            if not lv:
                continue
            for fr, kind, level in check_sr(lv):
                period = lv[fr][2]
                key = f"{t}-sr-{fr}-{kind}-{period:%Y-%m-%d}"
                if key in already_sent:
                    continue
                already_sent.add(key)
                _append_line(SR_SENT_FILE, key)
                hits += 1
                send_telegram(_sr_message(t, fr, kind, level, lv), kind="sr")
        except Exception as e:
            log(f"{t}: خطأ دعم/مقاومة - {e}")
    free_memory()
    log(f"[{datetime.now():%H:%M}] دعم ومقاومة الأسبوع/الشهر: خلص الفحص - {hits} تنبيه جديد")


